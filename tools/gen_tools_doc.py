"""Generate docs/TOOLS.md — the list of all MCP tools with parameters, from the adapter's live MCP schemas — and the tool
table in README.md / README.ru.md / README.zh-CN.md (between the `<!-- tools:start -->` and `<!-- tools:end -->` marks).
Groups are the adapter's modules (registry.MODULES, in that order) — a new tool lands in its module's group by itself.

    .venv\\Scripts\\python.exe tools\\gen_tools_doc.py
"""
import asyncio
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.environ["SWMCP_DOCS"] = "full"   # the generated files carry the full descriptions
os.environ["SWMCP_TOOLS"] = "all"   # and every tool group, also the ones that are off by default
os.environ["SWMCP_USAGE_LOG"] = "off"
sys.path.insert(0, os.path.join(REPO, "adapters", "claude"))
import registry  # noqa: E402
import server  # noqa: E402
import tool_groups  # noqa: E402

# module → (English title, Russian title, Chinese title)
TITLES = {
    "tools_document": ("Documents and files", "Документы и файлы", "文档与文件"),
    "tools_sketch": ("Sketches", "Эскизы", "草图"),
    "tools_features": ("Part features", "Элементы детали", "零件特征"),
    "tools_drawing": ("Drawings", "Чертежи", "工程图"),
    "tools_analysis": ("Reading and checking the model", "Чтение модели и проверка", "读取与检查模型"),
    "tools_core": ("Background jobs and batches", "Фоновые задачи и пакеты", "后台任务与批处理"),
    "tools_assembly": ("Assemblies", "Сборки", "装配体"),
    "tools_sheet_metal": ("Sheet metal", "Листовой металл", "钣金"),
    "tools_simulation": ("Strength: SOLIDWORKS Simulation and hand checks", "Прочность: SOLIDWORKS Simulation и ручные проверки", "强度：SOLIDWORKS Simulation 与手算校核"),
    "tools_weldments": ("Weldments", "Сварные конструкции", "焊件"),
    "tools_images": ("Pictures of the model", "Изображения модели", "模型图片"),
    "tool_docs": ("Help", "Справка", "帮助"),
    "tool_groups": ("Tool groups", "Группы инструментов", "工具组"),
}


def _title(module_name: str, lang: int = 0) -> str:
    if module_name in TITLES:
        return TITLES[module_name][lang]
    doc = (sys.modules.get(module_name).__doc__ or module_name).strip().splitlines()[0]
    return doc.split("—")[-1].split(":")[0].strip().rstrip(".")


def _readme_table(order, by_module, tools, lang):
    head = [("| Group | Tools |", "| Группа | Инструменты |", "| 分组 | 工具 |")[lang], "|---|---|"]
    off = (" · *on request*", " · *по запросу*", " · *按需开启*")[lang]
    rows = []
    for m in order:
        names = [n for n in by_module.get(m, []) if n in tools]
        if not names:
            continue
        group = tool_groups.MODULE_GROUP.get(m)
        note = off if group and group not in tool_groups.DEFAULT_ON else ""
        rows.append(f"| **{_title(m, lang)}** ({len(names)}){note} | " + ", ".join(f"`{n}`" for n in names) + " |")
    return "\n".join(head + rows)


def _update_readme(name, table):
    path = os.path.join(REPO, name)
    if not os.path.isfile(path):
        return
    s = open(path, encoding="utf-8").read()
    new = re.sub(r"<!-- tools:start -->.*?<!-- tools:end -->",
                 lambda m: "<!-- tools:start -->\n" + table + "\n<!-- tools:end -->", s, flags=re.S)
    if new != s:
        open(path, "w", encoding="utf-8", newline="\n").write(new)
        print(f"{path}: tool table updated")


def main():
    tools = {t.name: t for t in asyncio.run(server.mcp.list_tools())}
    by_module = {}
    for t in server.mcp._tool_manager.list_tools():   # registration order; the same private hook server.py uses
        by_module.setdefault(t.fn.__module__, []).append(t.name)
    order = [m.__name__ for m in registry.MODULES] + sorted(set(by_module) - {m.__name__ for m in registry.MODULES})

    lines = ["# Alchemist for SOLIDWORKS — MCP tools", "",
             f"**{len(tools)}** tools. Generated by `tools/gen_tools_doc.py` from the MCP schemas — do not edit by hand. "
             "Groups are the adapter's modules (`registry.MODULES`).", "",
             "Units: lengths in **millimetres**, angles in **degrees** in every tool (the adapter converts to SI for the "
             "server); Simulation — **mm, N, MPa**. An answer is one JSON object, an error is `CODE | message`.", ""]
    for module_name in order:
        names = [n for n in by_module.get(module_name, []) if n in tools]
        if not names:
            continue
        lines.extend([f"## {_title(module_name)} ({len(names)})", ""])
        for n in names:
            t = tools[n]
            desc = " ".join((t.description or "").split())
            props = (t.input_schema or {}).get("properties", {})
            req = set((t.input_schema or {}).get("required", []))
            ps = ", ".join(("**" + k + "**" if k in req else k) for k in props)
            lines.append(f"- **`{n}`**({ps}) — {desc}")
        lines.append("")
    path = os.path.join(REPO, "docs", "TOOLS.md")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print(f"{path}: {len(tools)} tools in {sum(1 for m in order if by_module.get(m))} groups")
    _update_readme("README.md", _readme_table(order, by_module, tools, 0))
    _update_readme("README.ru.md", _readme_table(order, by_module, tools, 1))
    _update_readme("README.zh-CN.md", _readme_table(order, by_module, tools, 2))


if __name__ == "__main__":
    main()
